export const TERMINAL_COMPONENTS: readonly ComponentContract[] =
  definitions.map(
    ([
      name,
      purpose,
      states,
      actions,
      focus,
      keyboard,
      linear,
      resize,
      example,
    ]) => ({
      id: `terminal.${name}`,
      version: "1.0.0",
      name,
      purpose,
      states: states.split(","),
      actions: actions.split(","),
      focus,
      keyboard,
      linear,
      resize,
      requiredCapabilities: [],
      tokens: Object.values(SEMANTIC_ROLES),
      example,
    }),
  );
export function getTerminalComponent(query = "") {
  const q = query.toLocaleLowerCase();
  return TERMINAL_COMPONENTS.filter((c) =>
    [c.id, c.name, c.purpose, c.keyboard]
      .join(" ")
      .toLocaleLowerCase()
      .includes(q),
  );
}
